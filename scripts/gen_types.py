"""Generate frontend/lib/api-types.ts from the backend's Pydantic schemas.

Run from the repository root:  backend/.venv/bin/python scripts/gen_types.py
"""

from __future__ import annotations

import sys
from pathlib import Path

from pydantic import BaseModel

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.schemas import common, domain  # noqa: E402

HEADER = "// Generated by scripts/gen_types.py from backend/app/schemas. Do not edit by hand.\n\n"


def ts_type(schema: dict, defs: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "anyOf" in schema:
        parts = []
        for s in schema["anyOf"]:
            t = ts_type(s, defs)
            if t not in parts:
                parts.append(t)
        return " | ".join(parts)
    if "enum" in schema:
        return " | ".join(f'"{v}"' if isinstance(v, str) else str(v) for v in schema["enum"])
    if "const" in schema:
        return f'"{schema["const"]}"'
    t = schema.get("type")
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        inner = ts_type(schema.get("items", {}), defs)
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        add = schema.get("additionalProperties")
        if isinstance(add, dict) and add:
            return f"Record<string, {ts_type(add, defs)}>"
        return "Record<string, unknown>"
    return "unknown"


def interface(name: str, schema: dict, defs: dict) -> str:
    lines = [f"export interface {name} {{"]
    required = set(schema.get("required", []))
    for prop, s in schema.get("properties", {}).items():
        opt = "" if prop in required else "?"
        lines.append(f"  {prop}{opt}: {ts_type(s, defs)};")
    lines.append("}")
    return "\n".join(lines)


def main() -> None:
    models = []
    for mod in (common, domain):
        for name in dir(mod):
            obj = getattr(mod, name)
            if isinstance(obj, type) and issubclass(obj, BaseModel) and obj.__module__ == mod.__name__:
                models.append(obj)
    seen: dict[str, str] = {}
    for m in sorted(models, key=lambda c: c.__name__):
        mode = "serialization" if m.__name__.endswith("Out") else "validation"
        schema = m.model_json_schema(mode=mode, ref_template="#/$defs/{model}")
        defs = schema.pop("$defs", {})
        for dname, d in defs.items():
            if dname not in seen and d.get("type") == "object":
                seen[dname] = interface(dname, d, defs)
            elif dname not in seen and "enum" in d:
                seen[dname] = f"export type {dname} = {ts_type(d, defs)};"
        if schema.get("type") == "object":
            seen[m.__name__] = interface(m.__name__, schema, defs)
    out = ROOT / "frontend" / "lib" / "api-types.ts"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(HEADER + "\n\n".join(seen[k] for k in sorted(seen)) + "\n")
    print(f"Wrote {len(seen)} types to {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
